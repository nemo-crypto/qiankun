const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const express = require('express')
const { spaFallback } = require('../scripts/spa-fallback.cjs')
const { port } = require('../config/settings.cjs')
test('无效端口立即报错', () => {
  assert.equal(port(undefined, 8080), 8080)
  for (const invalid of ['abc', '0', '65536', '3.5']) assert.throws(() => port(invalid, 8080))
})
test('深层路由返回页面，缺失资源与写请求不返回伪 HTML', async t => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'qiankun-test-'))
  await fs.writeFile(path.join(folder, 'index.html'), '<html>app</html>')
  const app = express(); app.use(spaFallback(folder))
  const server = app.listen(0, '127.0.0.1')
  await new Promise(resolve => server.once('listening', resolve))
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await fs.rm(folder, { recursive: true }) })
  const base = `http://127.0.0.1:${server.address().port}`
  const page = await fetch(base + '/sub-vue/about', { headers: { accept: 'text/html' } })
  assert.equal(page.status, 200)
  assert.match(await page.text(), /<html>/)
  assert.equal((await fetch(base + '/missing.js')).status, 404)
  assert.equal((await fetch(base + '/save', { method: 'POST' })).status, 404)
  assert.equal((await fetch(base + '/api', { headers: { accept: 'application/json' } })).status, 404)
})
